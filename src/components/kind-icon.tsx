import {
  Activity,
  Archive,
  BadgeCheck,
  Box,
  CalendarClock,
  Copy,
  Cylinder,
  Database,
  FileCog,
  FolderTree,
  Gauge,
  Globe,
  HardDrive,
  KeyRound,
  Layers,
  Link,
  ListChecks,
  Network,
  Puzzle,
  Rocket,
  Server,
  Shield,
  ShieldCheck,
  UserRound,
} from "lucide-react";

const ICONS: Record<string, React.ComponentType> = {
  pods: Box,
  deployments: Rocket,
  statefulsets: Database,
  daemonsets: Copy,
  jobs: ListChecks,
  cronjobs: CalendarClock,
  services: Network,
  ingresses: Globe,
  configmaps: FileCog,
  secrets: KeyRound,
  nodes: Server,
  namespaces: FolderTree,
  events: Activity,
  replicasets: Layers,
  networkpolicies: Shield,
  horizontalpodautoscalers: Gauge,
  poddisruptionbudgets: ShieldCheck,
  persistentvolumeclaims: HardDrive,
  persistentvolumes: Cylinder,
  storageclasses: Archive,
  serviceaccounts: UserRound,
  roles: BadgeCheck,
  clusterroles: BadgeCheck,
  rolebindings: Link,
  clusterrolebindings: Link,
};

/** The icon for a kind, by its id; custom kinds share a puzzle piece. */
export function KindIcon({ kind }: { kind: string }) {
  const Icon = ICONS[kind] ?? Puzzle;
  return <Icon />;
}
